import type { ReactNode } from 'react';
import clsx from 'clsx';
import { toneChip, type Tone } from './tone';

export interface BadgeProps {
  tone?: Tone;
  icon?: ReactNode;
  children: ReactNode;
  className?: string;
  /** Compact uppercase mono label style (default) vs sentence case. */
  mono?: boolean;
  title?: string;
}

/** Small hairline chip. Use semantic wrappers (StatusBadge, SeverityBadge…) for enums. */
export function Badge({ tone = 'neutral', icon, children, className, mono = true, title }: BadgeProps) {
  return (
    <span
      title={title}
      className={clsx(
        'inline-flex h-5 shrink-0 items-center gap-1 whitespace-nowrap rounded-sm border px-1.5 [&>svg]:h-3 [&>svg]:w-3',
        mono ? 'font-mono text-[0.65rem] font-medium uppercase tracking-[0.06em]' : 'text-xs',
        toneChip[tone],
        className,
      )}
    >
      {icon}
      {children}
    </span>
  );
}

/** Explicit "SIMULATED" source marker used wherever simulated telemetry is displayed. */
export function SimulatedBadge({ className }: { className?: string }) {
  return (
    <Badge tone="steel" className={className} title="Generated by the PowerPulse simulator — not real IoT telemetry">
      Simulated
    </Badge>
  );
}
