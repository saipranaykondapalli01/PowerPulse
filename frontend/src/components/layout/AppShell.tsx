import { useEffect, useState } from 'react';
import { Link, NavLink, Outlet, useLocation } from 'react-router-dom';
import { Menu, PanelLeftClose, PanelLeftOpen } from 'lucide-react';
import clsx from 'clsx';
import { useAuth } from '@/context/AuthContext';
import { useSimulationStatus } from '@/hooks/useMonitoring';
import { ToastProvider } from '@/components/ui/Toast';
import { Drawer } from '@/components/ui/Drawer';
import { IconButton } from '@/components/ui/IconButton';
import { links } from '@/utils/links';
import { NAV_GROUPS, NAV_ITEMS, groupForPath, titleForPath } from './navItems';
import { GlobalSearch } from './GlobalSearch';
import { NotificationBell } from './NotificationBell';
import { UserMenu } from './UserMenu';

const COLLAPSE_KEY = 'pp.sidebar.collapsed';

function readCollapsed(): boolean {
  try {
    return window.localStorage.getItem(COLLAPSE_KEY) === '1';
  } catch {
    return false;
  }
}

function Wordmark({ compact }: { compact?: boolean }) {
  return (
    <Link to="/dashboard" className="flex items-center gap-2 rounded-sm text-fg" aria-label="PowerPulse dashboard">
      <span aria-hidden="true" className="flex h-6 w-6 shrink-0 items-center justify-center rounded-sm bg-accent">
        <svg viewBox="0 0 16 16" className="h-3.5 w-3.5 text-ink" fill="none" stroke="currentColor" strokeWidth="1.8">
          <path d="M1 9h3l2-5 3 9 2-6 1.5 2H15" strokeLinecap="round" strokeLinejoin="round" />
        </svg>
      </span>
      {!compact && <span className="font-display text-sm font-semibold tracking-tight">PowerPulse</span>}
    </Link>
  );
}

function NavList({ collapsed, onNavigate }: { collapsed?: boolean; onNavigate?: () => void }) {
  const { hasRole } = useAuth();
  const items = NAV_ITEMS.filter((n) => !n.roles || hasRole(...n.roles));
  return (
    <div className="flex flex-col gap-4">
      {NAV_GROUPS.map((group) => {
        const groupItems = items.filter((n) => n.group === group);
        if (groupItems.length === 0) return null;
        return (
          <div key={group}>
            <p
              className={clsx(
                'mb-1 px-2.5 font-mono text-[0.625rem] uppercase tracking-[0.12em] text-fg-muted',
                collapsed && 'sr-only',
              )}
            >
              {group}
            </p>
            <ul className="flex flex-col gap-px">
              {groupItems.map(({ to, label, Icon }) => (
                <li key={to}>
                  <NavLink
                    to={to}
                    onClick={onNavigate}
                    title={collapsed ? label : undefined}
                    className={({ isActive }) =>
                      clsx(
                        'relative flex h-8 items-center gap-2.5 rounded-sm px-2.5 text-[0.8125rem] transition-colors duration-fast',
                        isActive
                          ? 'bg-canvas font-medium text-fg shadow-[inset_0_0_0_1px_rgb(var(--line))]'
                          : 'text-fg-muted hover:bg-raised/60 hover:text-fg',
                        collapsed && 'justify-center px-0',
                      )
                    }
                  >
                    {({ isActive }) => (
                      <>
                        {/* Active marker: lime rail + surface + weight, so state is never color-only. */}
                        {isActive && <span aria-hidden="true" className="absolute inset-y-1.5 left-0 w-[3px] rounded-r-sm bg-accent" />}
                        <Icon aria-hidden="true" className={clsx('h-4 w-4 shrink-0', isActive ? 'text-fg' : 'text-fg-muted')} />
                        <span className={clsx(collapsed && 'sr-only')}>{label}</span>
                      </>
                    )}
                  </NavLink>
                </li>
              ))}
            </ul>
          </div>
        );
      })}
    </div>
  );
}

/** "SIMULATED DATA" pill with simulator state; links to the dashboard simulation panel. */
function SimulatedIndicator() {
  const sim = useSimulationStatus();
  const running = sim.data?.running;
  return (
    <Link
      to={links.simulationPanel}
      title="All telemetry is generated by the PowerPulse simulator — not real IoT data. Open simulation controls."
      className="hidden h-7 items-center gap-1.5 rounded-sm border border-steel/40 bg-steel/10 px-2 font-mono text-[0.65rem] font-medium uppercase tracking-[0.08em] text-steel hover:bg-steel/20 sm:inline-flex"
    >
      <span
        aria-hidden="true"
        className={clsx('h-1.5 w-1.5 rounded-full', running ? 'animate-pulse bg-accent motion-reduce:animate-none' : 'bg-offline')}
      />
      Simulated data
      {sim.data && <span className="text-fg-muted">· {running ? 'live' : 'paused'}</span>}
    </Link>
  );
}

/** Authenticated application frame: sidebar nav, top bar (title, search, bell, user), toasts. */
export function AppShell() {
  const [collapsed, setCollapsed] = useState(readCollapsed);
  const [mobileOpen, setMobileOpen] = useState(false);
  const { pathname } = useLocation();
  const title = titleForPath(pathname);
  const group = groupForPath(pathname);

  useEffect(() => {
    document.title = `${title} · PowerPulse`;
  }, [title]);

  useEffect(() => {
    setMobileOpen(false);
  }, [pathname]);

  const toggleCollapsed = () => {
    setCollapsed((c) => {
      try {
        window.localStorage.setItem(COLLAPSE_KEY, c ? '0' : '1');
      } catch {
        // storage unavailable — keep in-memory state only
      }
      return !c;
    });
  };

  return (
    <ToastProvider>
      <div className="min-h-screen bg-canvas font-sans text-fg [color-scheme:light]">
        <a
          href="#main-content"
          className="sr-only z-[70] rounded-sm bg-accent px-3 py-2 text-sm font-medium text-ink focus:not-sr-only focus:fixed focus:left-3 focus:top-3"
        >
          Skip to content
        </a>

        {/* Desktop sidebar */}
        <aside
          className={clsx(
            'fixed inset-y-0 left-0 z-30 hidden flex-col border-r border-line bg-panel transition-[width] duration-base ease-out md:flex',
            collapsed ? 'w-14' : 'w-56',
          )}
        >
          <div className={clsx('flex h-14 items-center border-b border-line', collapsed ? 'justify-center' : 'px-4')}>
            <Wordmark compact={collapsed} />
          </div>
          <nav aria-label="Primary" className="flex-1 overflow-y-auto px-2 py-3">
            <NavList collapsed={collapsed} />
          </nav>
          <div className={clsx('border-t border-line p-2', collapsed && 'flex justify-center')}>
            <IconButton
              label={collapsed ? 'Expand sidebar' : 'Collapse sidebar'}
              icon={collapsed ? <PanelLeftOpen /> : <PanelLeftClose />}
              onClick={toggleCollapsed}
              aria-expanded={!collapsed}
            />
          </div>
        </aside>

        {/* Mobile nav drawer */}
        <Drawer open={mobileOpen} onClose={() => setMobileOpen(false)} title="Navigation" side="left" widthClass="w-64">
          <div className="border-b border-line px-4 py-3">
            <Wordmark />
          </div>
          <nav aria-label="Primary" className="px-2 py-3">
            <NavList onNavigate={() => setMobileOpen(false)} />
          </nav>
        </Drawer>

        <div className={clsx('flex min-h-screen min-w-0 flex-col transition-[padding] duration-base ease-out', collapsed ? 'md:pl-14' : 'md:pl-56')}>
          <header className="sticky top-0 z-20 flex h-14 items-center gap-2 border-b border-line bg-canvas/90 px-3 backdrop-blur sm:gap-3 sm:px-5">
            <IconButton
              label="Open navigation"
              icon={<Menu />}
              className="md:hidden"
              onClick={() => setMobileOpen(true)}
              aria-expanded={mobileOpen}
            />
            <nav aria-label="Breadcrumb" className="hidden min-w-0 sm:block">
              <ol className="flex items-center gap-1.5 truncate text-sm">
                {group && (
                  <li className="flex items-center gap-1.5 font-mono text-label uppercase text-fg-muted">
                    {group}
                    <span aria-hidden="true" className="text-line-strong">/</span>
                  </li>
                )}
                <li aria-current="page" className="truncate font-display font-semibold tracking-tight text-fg">
                  {title}
                </li>
              </ol>
            </nav>
            <div className="ml-auto flex min-w-0 flex-1 items-center justify-end gap-1.5 sm:gap-2">
              <GlobalSearch className="w-full max-w-xs" />
              <SimulatedIndicator />
              <NotificationBell />
              <UserMenu />
            </div>
          </header>
          <main id="main-content" tabIndex={-1} className="min-w-0 flex-1 px-4 py-5 outline-none sm:px-6 sm:py-6 xl:px-8">
            <Outlet />
          </main>
        </div>
      </div>
    </ToastProvider>
  );
}
